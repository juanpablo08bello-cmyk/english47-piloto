-- Migracion PostgreSQL 002 (version 2): menu propio de Mesas 2.0.
-- NO esta aplicada a ninguna base. Antes de aplicarla en produccion: pg_dump (ver docs/reforma/31-api-mesas.md).
-- Solo AGREGA una tabla y un indice; no toca ninguna fila ni columna existente.
-- Va con nombres calificados (english47.) para que funcione igual desde `npm run db:init` o pegada en el editor SQL.
-- Copia equivalente para SQLite: tabla menu_items en server/db.js (SCHEMA, version 4).
CREATE TABLE IF NOT EXISTS english47.menu_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES english47.users(id) ON DELETE CASCADE,
  restaurant_id TEXT NOT NULL DEFAULT 'propio',
  sort_order INTEGER NOT NULL DEFAULT 0,
  name TEXT NOT NULL,
  name_key TEXT NOT NULL,
  category TEXT NOT NULL CHECK (category IN ('entrada','principal','guarnicion','postre','bebida','alcohol','vino')),
  description TEXT NOT NULL DEFAULT '',
  allergens TEXT NOT NULL DEFAULT '',
  price_cents INTEGER CHECK (price_cents IS NULL OR (price_cents >= 0 AND price_cents <= 999999)),
  created_at TEXT NOT NULL,
  UNIQUE (user_id, restaurant_id, name_key)
);
CREATE INDEX IF NOT EXISTS idx_menu_items_owner ON english47.menu_items(user_id, restaurant_id, sort_order);

-- Permisos del rol de ejecucion, solo si ya existe (en una base nueva los da el final de supabase-setup.sql).
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'english47_app') THEN
    GRANT SELECT, INSERT, UPDATE, DELETE ON english47.menu_items TO english47_app;
    GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA english47 TO english47_app;
  END IF;
END $$;
