// Frases que cambian según el pedido: el objetivo toma el dato de la traducción.
const DYNAMIC = [
  [/, got it\. Anything else\?$/, (es) => `Repite el término (${es.split(',')[0].toLowerCase()}) y pregunta si quiere algo más.`],
  [/^I recommend the /, (es) => `Recomiéndale ${es.replace(/^Le recomiendo /, '').replace(/\.$/, '')}.`],
  [/^Let me confirm\. One /, (es) => `Confirma el pedido: ${es.replace(/^Déjeme confirmar\. /, '').replace(/\.$/, '').toLowerCase()}.`],
  [/^Okay, the .*I will tell the kitchen\.$/, (es) => `Confirma que ahora es ${es.replace(/^Bien, /, '').replace(/\. Le aviso a la cocina\.$/, '')} y dile que avisarás a la cocina.`],
  [/^We have /, (es) => `Dile que tienen ${es.replace(/^Tenemos /, '').replace(/\.$/, '')}.`],
];

/** Devuelve el objetivo de una frase del alumno, o null si no existe uno escrito. */
export function goalFor({ en, es }) {
  if (Object.hasOwn(GOALS, en)) return GOALS[en];
  const dynamic = DYNAMIC.find(([re]) => re.test(en));
  return dynamic ? dynamic[1](es) : null;
}
