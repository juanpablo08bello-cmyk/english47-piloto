export function applyAudit(entries) {
  const ids = new Set(entries.map((e) => e.id));
  for (const id of Object.keys(ALT_AUDIT)) {
    if (!ids.has(id)) throw new Error(`Auditoria: entrada inexistente ${id}`);
  }
  return entries.map((entry) => {
    const audit = ALT_AUDIT[entry.id] ?? {};
    const moved = new Set([...(audit.related ?? []), ...(audit.examples ?? []), ...(audit.contrasts ?? []).map((c) => c.wrong)].map((s) => s.toLowerCase()));
    return {
      ...entry,
      alts: entry.alts.filter((a) => !moved.has(a.toLowerCase())),
      related: audit.related ?? [],
      examples: audit.examples ?? [],
      contrasts: audit.contrasts ?? [],
    };
  });
}
