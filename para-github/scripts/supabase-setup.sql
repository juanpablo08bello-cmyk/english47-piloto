BEGIN;
CREATE SCHEMA english47;
REVOKE ALL ON SCHEMA english47 FROM PUBLIC;
SET LOCAL search_path TO english47, pg_catalog;
CREATE TABLE schema_versions (version integer PRIMARY KEY);

